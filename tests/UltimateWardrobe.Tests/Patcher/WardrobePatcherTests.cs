    [Fact]
    public async Task Build_LockedExportFolder_ThrowsPatchException()
    {
        using var dir = new TestTempDir();
        var (overhaul, library) = CreateE2eWorld(dir);
        var outputDir = Path.Combine(dir.Root, "Locked");
        var patcher = new WardrobePatcher();

        // A previous export left a file held with FileShare.None: the clean-before-write step fails.
        var modDir = Path.Combine(outputDir, ModName);
        Directory.CreateDirectory(modDir);
        using (new FileStream(Path.Combine(modDir, "held.bin"), FileMode.Create, FileAccess.ReadWrite, FileShare.None))
        {
            var ex = await Assert.ThrowsAsync<PatchException>(() => patcher.BuildAsync(overhaul, library, outputDir));

            Assert.Contains("clear", ex.Message, StringComparison.OrdinalIgnoreCase);
        }
    }

    [Fact]
    public async Task Build_MissingCatalog_ThrowsPatchException_BeforeAnyOutputIsTouched()
    {
        using var dir = new TestTempDir();
        SyntheticSkyrimMods.WriteMiniUniverse(dir.Root);
        var donor = WriteDonor(dir.Root, "donor-e2e", new[] { "meshes/donor/iron/m/cuirass.nif" });

        var projectId = Guid.NewGuid();
        var overhaul = new Overhaul(Guid.NewGuid(), "NoCatalog", projectId,
            new VanillaCatalogSource(dir.Root, new[] { SyntheticSkyrimMods.MiniUniverseFileName }));
        var library = MakeLibrary(donor.Asset);
        var outputDir = Path.Combine(dir.Root, "NoCatalogExport");

        await Assert.ThrowsAsync<PatchException>(() =>
            new WardrobePatcher().BuildAsync(overhaul, library, outputDir));

        Assert.False(Directory.Exists(Path.Combine(outputDir, "UltimateWardrobe - NoCatalog")));
    }

