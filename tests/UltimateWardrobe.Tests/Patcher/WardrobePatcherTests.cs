    private static Catalog CreateCatalog(string root)
    {
        var cuirass = new Variant(Gender.Male, WeightClass.Heavy, new[]
        {
            new Piece("IronCuirass", SyntheticSkyrimMods.MiniIronCuirassKey.ID, "32 Body", "IronCuirassAA", SyntheticSkyrimMods.MiniIronCuirassMalePath),
        });
        var helmet = new Variant(Gender.Male, WeightClass.Heavy, new[]
        {
            new Piece("IronHelmet", SyntheticSkyrimMods.MiniIronHelmetKey.ID, "32 Body", "IronHelmetAA", "meshes/armor/mini/IronHelmet/male.nif"),
        });

        return new Catalog(
            new VanillaCatalogSource(root, new[] { SyntheticSkyrimMods.MiniUniverseFileName }),
            new[] { new ArmorSet("IronArmor", "Iron", new[] { cuirass }), new ArmorSet("HelmetSet", "Helmet", new[] { helmet }) });
    }

    private static (string Directory, DonorAsset Asset) WriteDonor(
        string parent,
        string name,
        IReadOnlyList<string> files,
        IReadOnlyList<string>? bodySlide = null,
        IReadOnlyList<string>? physics = null,
        DonorAssetKind kind = DonorAssetKind.FullReplacer)
    {
        var directory = Path.Combine(parent, name);
        Directory.CreateDirectory(directory);

        var manifest = new List<DonorFileEntry>(files.Count);
        foreach (var file in files)
        {
            WriteAndCreate(file, directory);
            manifest.Add(new DonorFileEntry(file, new FileInfo(Path.Combine(directory, file.Replace('/', Path.DirectorySeparatorChar))).Length));
        }

        var asset = new DonorAsset(
            Guid.NewGuid(),
            name + ".7z",
            directory,
            DateTime.UtcNow,
            "hash-" + name,
            kind,
            fileManifest: manifest,
            detectedBodySlideFiles: bodySlide ?? Array.Empty<string>(),
            detectedPhysicsFiles: physics ?? Array.Empty<string>());

        return (directory, asset);
    }

    private static void WriteAndCreate(string relativePath, string root)
    {
        var full = Path.Combine(root, relativePath.Replace('/', Path.DirectorySeparatorChar));
        var parent = Path.GetDirectoryName(full);
        if (!string.IsNullOrEmpty(parent))
        {
            Directory.CreateDirectory(parent);
        }

        File.WriteAllText(full, Path.GetFileName(root) + "::" + relativePath);
    }

    private static UltimateWardrobe.Core.Domain.DonorLibrary MakeLibrary(params DonorAsset[] assets)
    {
        var library = new UltimateWardrobe.Core.Domain.DonorLibrary(Guid.NewGuid());
        library.Assets.AddRange(assets);
        return library;
    }

    private static IReadOnlyList<string> OutputTree(string root)
    {
        return Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories)
            .Select(f => Path.GetRelativePath(root, f).Replace('\\', '/'))
            .OrderBy(p => p, StringComparer.Ordinal)
            .ToArray();
    }
