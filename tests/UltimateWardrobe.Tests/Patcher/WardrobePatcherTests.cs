    [Fact]
    public async Task Build_EndToEnd_CreatesModFolder_PluginMetaAndReport()
    {
        using var dir = new TestTempDir();
        var (overhaul, library) = CreateE2eWorld(dir);
        var outputDir = Path.Combine(dir.Root, "Output");
        var exportDir = Path.Combine(outputDir, ModName);
        var reports = new List<PatchProgress>();

        var result = await new WardrobePatcher().BuildAsync(overhaul, library, outputDir, new Progress<PatchProgress>(reports.Add));

        // Layout: the esp + meta.ini + the exact whitelisted sliced files, nothing else.
        var pluginPath = Path.Combine(exportDir, ModName + ".esp");
        Assert.Equal(pluginPath, result.PluginPath);
        Assert.True(File.Exists(pluginPath));
        Assert.Equal(ExpectedSlicedFiles, result.CopiedFiles);
        Assert.Equal(ExpectedOutputTree, OutputTree(exportDir));

        // Report numbers.
        var report = result.Report!;
        Assert.Equal(2, report.TotalMappings);
        Assert.Equal(2, report.ResolvedMappings);
        Assert.Equal(0, report.SkippedMappings);
        Assert.Equal(2, report.OverriddenRecords);
        Assert.Equal(ExpectedSlicedFiles, report.CopiedFiles);
        Assert.True(report.CopiedBytes > 0);
        Assert.Empty(report.Warnings);

        // The reopened esp: ESL gate on, overridden ARMA WorldModel slots, UW_ prefix, masters.
        using var reopened = SkyrimMod.CreateFromBinaryOverlay(pluginPath, SkyrimRelease.SkyrimSE);
        Assert.True(reopened.IsSmallMaster);
        Assert.Contains(SyntheticSkyrimMods.MiniUniverseKey, reopened.MasterReferences.Select(m => m.Master));

        var cuirass = reopened.ArmorAddons[SyntheticSkyrimMods.MiniIronCuirassAddonKey];
        Assert.Equal("UW_IronCuirassAA", cuirass.EditorID);
        Assert.Equal("meshes/donor/iron/m/cuirass.nif", cuirass.WorldModel!.Male!.File!.GivenPath);
        Assert.Equal("meshes/armor/mini/IronCuirass/female.nif", cuirass.WorldModel.Female!.File!.GivenPath);

        var helmet = reopened.ArmorAddons[SyntheticSkyrimMods.MiniIronHelmetAddonKey];
        Assert.Equal("UW_IronHelmetAA", helmet.EditorID);
        Assert.Equal("meshes/donor/iron/h/helmet.nif", helmet.WorldModel!.Male!.File!.GivenPath);
        Assert.Equal("meshes/armor/mini/IronHelmet/female.nif", helmet.WorldModel.Female!.File!.GivenPath);

        // meta.ini: section 4.6 layout with the mapped-set count and a non-empty generated stamp.
        var meta = File.ReadAllText(Path.Combine(exportDir, "meta.ini"));
        Assert.Contains("[General]", meta, StringComparison.Ordinal);
        Assert.Contains("name=UltimateWardrobe - E2eTest", meta, StringComparison.Ordinal);
        Assert.Contains("version=1.0.0", meta, StringComparison.Ordinal);
        Assert.Contains("category=Armor Replacer", meta, StringComparison.Ordinal);
        Assert.Contains("notes=Generated by UltimateWardrobe on ", meta, StringComparison.Ordinal);
        Assert.Contains("Overhaul: E2eTest, 2 sets mapped.", meta, StringComparison.Ordinal);
        var generated = File.ReadAllLines(Path.Combine(exportDir, "meta.ini")).Single(l => l.StartsWith("generated=", StringComparison.Ordinal));
        Assert.Matches(@"generated=\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} UTC", generated);

        // Progress: one coarse update per pipeline stage.
        Assert.Equal(5, reports.Count);
        Assert.Equal(new[] { "Resolve targets", "Prepare export folder", "Build esp plugin", "Copy donor files", "Write meta.ini" },
            reports.Select(p => p.Stage).ToArray());
        Assert.Equal(5, reports[^1].Completed);
        Assert.Equal(5, reports[^1].Total);
    }

