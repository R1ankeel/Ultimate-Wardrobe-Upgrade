    [Fact]
    public async Task Build_TwoRuns_ProduceIdenticalEspBytesAndReport()
    {
        using var dir = new TestTempDir();
        var (overhaul, library) = CreateE2eWorld(dir);
        var outputDir = Path.Combine(dir.Root, "Determinism");
        var patcher = new WardrobePatcher();

        var first = await patcher.BuildAsync(overhaul, library, outputDir);
        var firstEspBytes = File.ReadAllBytes(first.PluginPath);

        var second = await patcher.BuildAsync(overhaul, library, outputDir);

        Assert.Equal(firstEspBytes, File.ReadAllBytes(second.PluginPath));
        Assert.Equal(first.Report!.TotalMappings, second.Report!.TotalMappings);
        Assert.Equal(first.Report.ResolvedMappings, second.Report.ResolvedMappings);
        Assert.Equal(first.Report.SkippedMappings, second.Report.SkippedMappings);
        Assert.Equal(first.Report.OverriddenRecords, second.Report.OverriddenRecords);
        Assert.Equal(first.Report.CopiedFiles, second.Report.CopiedFiles);
        Assert.Equal(first.Report.CopiedBytes, second.Report.CopiedBytes);
        Assert.Equal(first.Report.Warnings.Count, second.Report.Warnings.Count);
    }

    [Fact]
    public async Task Build_ReExport_ClearsStaleFilesAndStaleMetaFields()
    {
        using var dir = new TestTempDir();
        var (overhaul, library) = CreateE2eWorld(dir);
        var outputDir = Path.Combine(dir.Root, "ReExport");
        var patcher = new WardrobePatcher();

        var firstEspBytes = File.ReadAllBytes((await patcher.BuildAsync(overhaul, library, outputDir)).PluginPath);

        // Plant stale/orphaned content from a previous export.
        var exportDir = Path.Combine(outputDir, ModName);
        var orphanMesh = Path.Combine(exportDir, "meshes", "orphan", "ghost.nif");
        Directory.CreateDirectory(Path.GetDirectoryName(orphanMesh)!);
        File.WriteAllText(orphanMesh, "stale-mesh");
        File.WriteAllText(Path.Combine(exportDir, "orphan.bsa"), "stale-archive");
        File.WriteAllText(Path.Combine(exportDir, "stray.txt"), "stale-stray");
        File.WriteAllText(Path.Combine(exportDir, "meta.ini"),
            "[General]\nname=Stale\nstalekey=yes\ngenerated=1970-01-01 00:00 'UTC'\n");

        await patcher.BuildAsync(overhaul, library, outputDir);

        // The output tree is exactly the whitelisted set again - stale files are gone - and the
        // esp is byte-identical to the first export.
        Assert.Equal(ExpectedOutputTree, OutputTree(exportDir));
        Assert.Equal(firstEspBytes, File.ReadAllBytes(Path.Combine(exportDir, ModName + ".esp")));

        var meta = File.ReadAllText(Path.Combine(exportDir, "meta.ini"));
        Assert.DoesNotContain("stalekey", meta, StringComparison.Ordinal);
        Assert.Matches(@"generated=\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} UTC",
            File.ReadAllLines(Path.Combine(exportDir, "meta.ini")).Single(l => l.StartsWith("generated=", StringComparison.Ordinal)));
    }

